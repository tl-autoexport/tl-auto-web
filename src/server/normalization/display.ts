export function hasKorean(value: unknown) {
  return KOREAN_RE.test(String(value ?? ""));
}

export function cleanDisplay(value: unknown, fallback = "-") {
  const text = String(value ?? "").replace(/\s+/g, " ").trim();
  if (!text || hasKorean(text)) return fallback;
  return text;
}

