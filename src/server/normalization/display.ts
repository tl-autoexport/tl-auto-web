export function translateTransmission(value: string | null | undefined) {
  const raw = String(value ?? "").trim().toLowerCase();
  if (!raw) return "-";
  if (raw.includes("오토") || raw.includes("auto") || raw.includes("a/t")) return "Автомат";
  if (raw.includes("수동") || raw.includes("manual") || raw.includes("m/t")) return "Механика";
  return cleanDisplay(value);
}

export function translateOption(value: string | null | undefined) {
  const text = String(value ?? "").trim();
  if (!text) return null;
  if (EXACT_OPTION_MAP[text]) return EXACT_OPTION_MAP[text];
  for (const [pattern, ru] of OPTION_MAP) {
    if (text.toLowerCase().includes(pattern.toLowerCase())) return ru;
  }
  return hasKorean(text) ? null : text;
}

export function translateHeyDealerText(value: string | null | undefined) {
  const text = String(value ?? "")
    .replace(/^[・•]\s*/, "")
    .replace(/^\d+\)\s*/, "")
    .replace(/^\*\s*/, "")
    .trim();
  if (!text) return null;
  return HEYDEALER_TEXT_MAP[text] ?? translateOption(text);
}

export function translateHeyDealerNote(value: string | null | undefined) {
  return String(value ?? "")
    .split(/\n+/)
    .map((line) => translateHeyDealerText(line))
    .filter((line): line is string => Boolean(line));
}

export function categorizeOption(
  original: string | null | undefined,
  translated: string | null | undefined,
) {
  const text = `${original ?? ""} ${translated ?? ""}`.toLowerCase();

  if (
    /(시트|сиден|салон|마사지|массаж)/i.test(text)
  ) {
    return "Сиденья";
  }

  if (
    /(에어백|abs|tcs|esc|tpms|ldws|차선|후측방|주차감지|카메라|어라운드|서라운드|크루즈|안전|подуш|безопас|парктрон|камер|полос|слеп|круиз|стабилиз|давлен)/i.test(
      text,
    )
  ) {
    return "Безопасность";
  }

  if (
    /(내비|네비|navigation|블루투스|bluetooth|usb|aux|av |모니터|hud|헤드업|스마트키|버튼시동|에어컨|오토 라이트|레인센서|하이패스|오디오|사운드|krell|bose|lexicon|навигац|климат|мультимед|проекцион|смарт-ключ|запуска|датчик дождя|аудиосистем)/i.test(
      text,
    )
  ) {
    return "Комфорт и мультимедиа";
  }

  if (
    /(선루프|파노라마|헤드램프|led|hid|트렁크|도어|미러|휠|루프랙|스티어링|핸들|패들|윈도우|커튼|블라인드|люк|панорам|фар|багажник|двер|зеркал|диск|рейлинг|рул|стеклопод|шторк)/i.test(
      text,
    )
  ) {
    return "Экстерьер и интерьер";
  }

  return "Дополнительные опции";
}

