export function optionGroupName(name: string) {
  const lower = name.toLowerCase();
  if (/(подогрев|вентиляция|сиден|климат|люк|крыша|багажник)/i.test(name)) return "Комфорт";
  if (/(контроль|удержание|ассистент|круиз|парков|стояноч|слеп|камера|обзор|led|фары)/i.test(name)) return "Безопасность";
  if (/(навигация|аудио|видеорегистратор|проекционный|смарт|ключ)/i.test(name)) return "Мультимедиа";
  if (/(диски|комплектация)/i.test(name) || lower.includes("m sport")) return "Экстерьер";
  return "Другое";
}

export function carDisplayTitle(car: {
  brand: string | null;
  model: string | null;
  badge?: string | null;
  badge_detail?: string | null;
}) {
  const badge = translateBadge(car.badge_detail) ?? translateBadge(car.badge);
  return [cleanDisplay(car.brand, ""), cleanDisplay(car.model, ""), badge].filter(Boolean).join(" ").trim();
}
